import SwiftUI

struct UsersView: View {
    @EnvironmentObject var appViewModel: AppViewModel

    @State private var newAllergen = ""
    @State private var showClearConfirm = false
    @FocusState private var isInputFocused: Bool

    private let green = Color(red: 0.48, green: 0.78, blue: 0.51)

    var body: some View {
        NavigationStack {
            Form {
                Section {
                    ForEach(Allergen.common, id: \.self) { name in
                        Button {
                            appViewModel.toggleAllergen(name)
                        } label: {
                            HStack {
                                Text(name)
                                    .foregroundStyle(.primary)
                                Spacer()
                                if appViewModel.isAllergenSelected(name) {
                                    Image(systemName: "checkmark.circle.fill")
                                        .foregroundStyle(green)
                                } else {
                                    Image(systemName: "circle")
                                        .foregroundStyle(.tertiary)
                                }
                            }
                            .contentShape(Rectangle())
                        }
                        .buttonStyle(.plain)
                    }
                } header: {
                    Text("Common allergens")
                } footer: {
                    Text("Recipes will avoid everything you select here.")
                }

                Section {
                    ForEach(appViewModel.customAllergens, id: \.self) { name in
                        Text(name)
                    }
                    .onDelete { offsets in
                        let names = offsets.map { appViewModel.customAllergens[$0] }
                        withAnimation {
                            appViewModel.removeAllergens(names)
                        }
                    }

                    HStack {
                        TextField("Add another, e.g. Kiwi", text: $newAllergen)
                            .focused($isInputFocused)
                            .submitLabel(.done)
                            .onSubmit(addNewAllergen)

                        Button("Add", action: addNewAllergen)
                            .disabled(newAllergen.trimmingCharacters(in: .whitespaces).isEmpty)
                    }
                } header: {
                    Text("Other allergies")
                } footer: {
                    Text("Add any other ingredient you need to avoid, including fruits. Swipe left to remove.")
                }

                if !appViewModel.allergens.isEmpty {
                    Section {
                        Button("Clear All Allergies", role: .destructive) {
                            showClearConfirm = true
                        }
                    }
                }

                Section {
                    Label {
                        Text("Recipes are generated by AI and may still contain mistakes. Always check ingredient labels if you have a serious allergy.")
                    } icon: {
                        Image(systemName: "exclamationmark.shield")
                            .foregroundStyle(.orange)
                    }
                    .font(.footnote)
                    .foregroundStyle(.secondary)
                }
            }
            .navigationTitle("My Allergies")
            .scrollDismissesKeyboard(.interactively)
            .confirmationDialog(
                "Clear all allergies?",
                isPresented: $showClearConfirm,
                titleVisibility: .visible
            ) {
                Button("Clear All", role: .destructive) {
                    withAnimation {
                        appViewModel.clearAllergens()
                    }
                }
            }
        }
    }

    private func addNewAllergen() {
        guard !newAllergen.trimmingCharacters(in: .whitespaces).isEmpty else { return }
        // Added, or already in the list – either way clear the field and hide the keyboard.
        appViewModel.addCustomAllergen(newAllergen)
        newAllergen = ""
        isInputFocused = false
    }
}

#Preview {
